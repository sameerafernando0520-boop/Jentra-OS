import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {loadApprovedInputs,PROJECT,BUNDLE} from './approved_management_installer.mjs';
import {hashBytes} from './runtime_contract.mjs';
import {financeFixtureSql} from './finance_cash_fixture_20261013_r5.mjs';
const root=fileURLToPath(new URL('../../',import.meta.url));
if(process.argv.length>2)throw Error('FIXED_FINANCE_FIXTURE_LOADER_REQUIRED');
await loadApprovedInputs();
const planPath='docs/verification/wave5/finance-cash-fixture-preparation-20261013-r5-a1.json';
const planBytes=await fs.readFile(path.join(root,planPath));
if(hashBytes(planBytes)!=='c1d11c1aa58aef646289060e6091c9c21f63176c0febca86823a6cb851fedd16')throw Error('EXACT_FINANCE_PLAN_REQUIRED');
const plan=JSON.parse(planBytes),peerPath='docs/verification/wave5/finance-cash-fixture-independent-peer-review-20261013-r5-a1.json';
const peerBytes=await fs.readFile(path.join(root,peerPath));
if(hashBytes(peerBytes)!=='7f58386dc871755534dd304e1353b7572b5552c492e51f2b1360914ea5d71710')throw Error('EXACT_FINANCE_FIXTURE_PEER_REQUIRED');
const peer=JSON.parse(peerBytes);
if(peer.fixtureVerdict!=='source-reviewed-for-exact-bounded-administration-fixture'||peer.checkCount!==21||peer.checks.some(c=>c.passed!==true))throw Error('FINANCE_FIXTURE_PEER_PASS_REQUIRED');
for(const binding of plan.sourceBindings)if(hashBytes(await fs.readFile(path.join(root,binding.path)))!==binding.sha256)throw Error('FINANCE_FIXTURE_SOURCE_DRIFT');
const query=await fs.readFile(path.join(root,plan.commit.path),'utf8');
if(hashBytes(query)!=='233cb3065796d3cc5174506db010b81f5499df5aaa0dba37cb3140fb49e557ab'||query!==financeFixtureSql({commit:true}))throw Error('EXACT_FINANCE_COMMIT_REQUIRED');
process.stdout.write(JSON.stringify({project_id:PROJECT,query,bundleSha256:BUNDLE,sqlSha256:hashBytes(query),fixtureIsAdministrative:true,userPostingProved:false})+'\n');
